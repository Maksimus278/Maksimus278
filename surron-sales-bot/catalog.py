def format_model_card(key: str) -> str:
    """Формирует подробную карточку модели в HTML для Telegram."""
    m = MODELS[key]
    specs = "\n".join(f"• <b>{label}:</b> {value}" for label, value in m["specs"])
    return (
        f"{m['emoji']} <b>{m['name']}</b>\n"
        f"<i>{m['tagline']}</i>\n\n"
        f"{m['description']}\n\n"
        f"<b>Технические характеристики</b>\n{specs}\n\n"
        f"<b>Кому подойдёт:</b> {m['best_for']}\n\n"
        f"💰 <b>Цена: {m['price']}</b>\n\n"
        f"Нажмите «Заказать», чтобы связаться с менеджером."
    )


